#!/usr/bin/env python3
"""台账一致性检查与统计生成（正向不变量）。

两个台账，职责分离：

  - known_open_items.md    未闭合 / 信息条目；0.1 状态统计 / 0.6 按模块统计；
  - known_closed_items.md  已闭合 / 不实现条目；0. 概览。

统计块是派生视图，唯一事实源是开放式台账各模块「### 索引」表的状态列，以及
已闭合台账的两个索引小节。手工维护统计必然漂移，因此由本工具生成，并在
make check 中校验：

  python3 tools/check_ledger.py --root . --check     # 不一致 → exit 1
  python3 tools/check_ledger.py --root . --write     # 重写两个台账的统计块
  python3 tools/check_ledger.py --root . --self-test # 负例自检（P13/C7）

结构不变量（附录 A.5）：
  - 开放式台账的模块索引只能出现未闭合状态；已闭合 / 不实现必须迁入已闭合台账；
  - 同一 ID 在两个台账合起来只能登记一次。

退出码：0 = 一致；1 = 违规；2 = 工具/输入错误。
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

OPEN_REL = "docs/design/known_open_items.md"
CLOSED_REL = "docs/design/known_closed_items.md"

# 开放式台账里允许出现的状态（附录 A.2 的未闭合状态 + 信息）。
OPEN_STATUSES = ["待决策", "待定位", "待验证", "待实现", "进行中", "待外部", "信息"]
CLOSED_STATUS = "已闭合"
NOT_IMPL_STATUS = "不实现"

STATUS_MEANING = {
    "待决策": "需要用户裁决",
    "待定位": "根因未明",
    "待验证": "实现完成，缺板端证据",
    "待实现": "功能/验证未开始",
    "进行中": "已做一部分",
    "待外部": "等硬件/测试源/第三方",
    "信息": "判定结论/维护不变量",
    "已闭合": "有证据且无剩余动作",
    "不实现": "用户明确不做",
}

# 前缀允许数字（如 L2P）：只允许 A-Z 会把 RISK-L2P-* 整类静默漏计。
ID_RE = re.compile(r"^(?:RISK|ISS)-[A-Z][A-Z0-9]*-\d+$")
MODULE_RE = re.compile(r"^## (\d+)\. (.+?)\s*$")

OPEN_STATS_HEADINGS = {
    "status": "### 0.1 状态统计",
    "module": "### 0.6 按模块统计（未闭合 + 信息）",
}
CLOSED_INDEX_HEADING = "## 1. 已闭合索引"
CLOSED_DETAIL_HEADING = "## 2. 已闭合详情"
NOT_IMPL_HEADING = "## 3. 不实现"
CLOSED_STATS_HEADING = "## 0. 概览"

BEGIN_LINE = (
    "<!-- ledger-stats:begin "
    "(generated by tools/check_ledger.py --write; do not edit by hand) -->"
)
END_LINE = "<!-- /ledger-stats:end -->"
BEGIN_RE = re.compile(r"^<!-- ledger-stats:begin")


class LedgerError(Exception):
    """输入台账结构不符合预期（工具错误，不是内容违规）。"""


def split_cells(line: str) -> list[str]:
    """按未转义的 | 切分表格行；单元格里的 \\| 是 Markdown 转义，不切。"""
    body = line.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|") and not body.endswith("\\|"):
        body = body[:-1]
    return [cell.strip() for cell in re.split(r"(?<!\\)\|", body)]


def parse_open(lines: list[str]) -> dict:
    """解析开放式台账的模块索引。"""
    modules: dict[int, dict] = {}
    module_rows: list[tuple[int, int, list[str]]] = []
    row_errors: list[str] = []

    cur_mod: int | None = None
    in_index = False

    for lineno, line in enumerate(lines, 1):
        if line.startswith("### 已闭合") or line.startswith("### 不实现"):
            row_errors.append(
                f"L{lineno}: 已闭合 / 不实现小节必须迁入 known_closed_items.md"
            )
        if line.startswith("# 附录 B"):
            row_errors.append(f"L{lineno}: 开放式台账不再保留附录 B")

        mod = MODULE_RE.match(line)
        if mod:
            cur_mod = int(mod.group(1))
            # 「## 0. 未闭合看板」是看板，不是模块，不能进 0.6 统计。
            if cur_mod == 0:
                in_index = False
                continue
            if cur_mod in modules:
                raise LedgerError(f"模块编号 {cur_mod} 重复（L{lineno}）")
            modules[cur_mod] = {"title": mod.group(2).strip()}
            in_index = False
            continue

        if line.startswith("### 索引"):
            in_index = True
            continue
        if line.startswith("### "):
            in_index = False
            continue
        if in_index and line.startswith("|") and not line.startswith("|---"):
            cells = split_cells(line)
            if len(cells) >= 3 and ID_RE.match(cells[0]):
                if len(cells) != 5:
                    row_errors.append(
                        f"L{lineno}: 模块索引行应有 5 列，实际 {len(cells)} 列"
                    )
                module_rows.append((lineno, cur_mod, cells))

    if not modules:
        raise LedgerError("开放式台账没有解析到任何模块分节（## N. 标题）")

    return {
        "modules": modules,
        "module_rows": module_rows,
        "row_errors": row_errors,
    }


def parse_closed(lines: list[str]) -> dict:
    """解析已闭合台账的已闭合 / 不实现索引小节。"""
    closed_rows: list[tuple[int, list[str]]] = []
    notimpl_rows: list[tuple[int, list[str]]] = []
    row_errors: list[str] = []

    section: str | None = None
    for lineno, line in enumerate(lines, 1):
        if line.startswith(CLOSED_INDEX_HEADING):
            section = "closed"
            continue
        if line.startswith(CLOSED_DETAIL_HEADING):
            section = "detail"
            continue
        if line.startswith(NOT_IMPL_HEADING):
            section = "notimpl"
            continue
        if line.startswith("## "):
            section = None
            continue
        if section in ("closed", "notimpl") and line.startswith("|"):
            if line.startswith("|---"):
                continue
            cells = split_cells(line)
            if len(cells) >= 3 and ID_RE.match(cells[0]):
                if len(cells) != 5:
                    row_errors.append(
                        f"L{lineno}: 已闭合台账索引行应有 5 列，实际 {len(cells)} 列"
                    )
                if section == "closed":
                    closed_rows.append((lineno, cells))
                else:
                    notimpl_rows.append((lineno, cells))

    return {
        "closed_rows": closed_rows,
        "notimpl_rows": notimpl_rows,
        "row_errors": row_errors,
    }


def validate(open_parsed: dict, closed_parsed: dict) -> list[str]:
    """结构不变量检查。返回错误清单。"""
    errors: list[str] = list(open_parsed["row_errors"])
    errors.extend(closed_parsed["row_errors"])
    seen: dict[str, list[int]] = {}

    for lineno, _, cells in open_parsed["module_rows"]:
        status = cells[2]
        if status not in OPEN_STATUSES:
            errors.append(
                f"L{lineno}: {cells[0]} 在模块索引中出现状态「{status}」；"
                "已闭合 / 不实现必须迁入 known_closed_items.md（A.5）"
            )
        seen.setdefault(cells[0], []).append(lineno)

    for rows in (closed_parsed["closed_rows"], closed_parsed["notimpl_rows"]):
        for lineno, cells in rows:
            seen.setdefault(cells[0], []).append(lineno)

    for ident, locs in sorted(seen.items()):
        if len(locs) > 1:
            where = "、".join(f"L{n}" for n in locs)
            errors.append(f"{ident} 重复登记：{where}（同一事项只能登记一次）")

    return errors


def counts(open_parsed: dict, closed_parsed: dict) -> tuple[dict, dict, int, int]:
    """按状态、按模块、已闭合数、不实现数。"""
    by_status = {status: 0 for status in OPEN_STATUSES}
    by_module: dict[int, dict[str, int]] = {
        num: {status: 0 for status in OPEN_STATUSES}
        for num in open_parsed["modules"]
    }

    for _, mod, cells in open_parsed["module_rows"]:
        status = cells[2]
        if status in by_status:
            by_status[status] += 1
        if mod in by_module and status in by_module[mod]:
            by_module[mod][status] += 1

    return (
        by_status,
        by_module,
        len(closed_parsed["closed_rows"]),
        len(closed_parsed["notimpl_rows"]),
    )


def render_open_status(
    by_status: dict[str, int], closed_count: int, notimpl_count: int
) -> list[str]:
    lines = ["| 状态 | 含义 | 数量 |", "|---|---|---:|"]
    for status in OPEN_STATUSES:
        lines.append(f"| {status} | {STATUS_MEANING[status]} | {by_status[status]} |")
    lines.extend(
        [
            "",
            "> 已闭合 / 不实现："
            f"{closed_count} / {notimpl_count} → "
            "[known_closed_items.md](known_closed_items.md)",
        ]
    )
    return lines


def render_open_module(
    open_parsed: dict, by_module: dict[int, dict[str, int]]
) -> list[str]:
    header = (
        "| 模块 | 待决策 | 待定位 | 待验证 | 待实现 | 进行中 | 待外部 | 信息 | 合计 |"
    )
    sep = "|---|---:|---:|---:|---:|---:|---:|---:|---:|"
    lines = [header, sep]
    for num in sorted(open_parsed["modules"]):
        title = open_parsed["modules"][num]["title"]
        values = [by_module[num][status] for status in OPEN_STATUSES]
        total = sum(values)
        cells = " | ".join(str(value) for value in values)
        lines.append(f"| {num}. {title} | {cells} | {total} |")
    return lines


def render_closed_overview(closed_count: int, notimpl_count: int) -> list[str]:
    return [
        "| 项 | 含义 | 数量 |",
        "|---|---:|---:|",
        f"| {CLOSED_STATUS} | {STATUS_MEANING[CLOSED_STATUS]} | {closed_count} |",
        f"| {NOT_IMPL_STATUS} | {STATUS_MEANING[NOT_IMPL_STATUS]} | {notimpl_count} |",
    ]


def rendered_blocks(
    open_parsed: dict, closed_parsed: dict
) -> tuple[dict[str, list[str]], list[str]]:
    by_status, by_module, closed_count, notimpl_count = counts(
        open_parsed, closed_parsed
    )
    open_blocks = {
        "status": render_open_status(by_status, closed_count, notimpl_count),
        "module": render_open_module(open_parsed, by_module),
    }
    closed_block = render_closed_overview(closed_count, notimpl_count)
    return open_blocks, closed_block


def locate_block(lines: list[str], heading: str) -> tuple[int, int]:
    """定位某标题下的统计块。返回 (start, end)，含首尾行。"""
    heading_idx = next(
        (idx for idx, line in enumerate(lines) if line.startswith(heading)), None
    )
    if heading_idx is None:
        raise LedgerError(f"找不到标题：{heading}")

    idx = heading_idx + 1
    while idx < len(lines) and lines[idx].strip() == "":
        idx += 1

    if idx < len(lines) and BEGIN_RE.match(lines[idx]):
        end = idx + 1
        while end < len(lines) and lines[end].strip() != END_LINE:
            end += 1
        if end >= len(lines):
            raise LedgerError(f"{heading} 的 ledger-stats 块缺少结束标记")
        return idx, end

    if idx >= len(lines) or not lines[idx].startswith("|"):
        raise LedgerError(f"{heading} 下既没有表格，也没有 ledger-stats 标记")

    end = idx
    while end + 1 < len(lines) and lines[end + 1].startswith("|"):
        end += 1
    return idx, end


def write_block(lines: list[str], heading: str, table: list[str]) -> None:
    """原地写入统计块（有标记替换，无标记插入并删除旧表）。"""
    heading_idx = next(
        (idx for idx, line in enumerate(lines) if line.startswith(heading)), None
    )
    if heading_idx is None:
        raise LedgerError(f"找不到标题：{heading}")

    idx = heading_idx + 1
    while idx < len(lines) and lines[idx].strip() == "":
        idx += 1

    if idx < len(lines) and BEGIN_RE.match(lines[idx]):
        end = idx + 1
        while end < len(lines) and lines[end].strip() != END_LINE:
            end += 1
        if end >= len(lines):
            raise LedgerError(f"{heading} 的 ledger-stats 块缺少结束标记")
        lines[idx : end + 1] = [BEGIN_LINE, *table, END_LINE]
        return

    if idx >= len(lines) or not lines[idx].startswith("|"):
        raise LedgerError(f"{heading} 下既没有表格，也没有 ledger-stats 标记")

    end = idx
    while end + 1 < len(lines) and lines[end + 1].startswith("|"):
        end += 1

    after = end + 1
    while after < len(lines) and lines[after].strip() == "":
        after += 1

    lines[heading_idx + 1 : after] = ["", BEGIN_LINE, *table, END_LINE, ""]


def check_files(open_lines: list[str], closed_lines: list[str]) -> list[str]:
    """结构检查 + 两个台账统计块的一致性。返回错误清单（空 = 通过）。"""
    open_parsed = parse_open(open_lines)
    closed_parsed = parse_closed(closed_lines)
    errors = validate(open_parsed, closed_parsed)
    if errors:
        return errors

    open_blocks, closed_block = rendered_blocks(open_parsed, closed_parsed)
    for key, heading in OPEN_STATS_HEADINGS.items():
        start, end = locate_block(open_lines, heading)
        actual = open_lines[start : end + 1]
        expected = [BEGIN_LINE, *open_blocks[key], END_LINE]
        if actual != expected:
            errors.append(
                f"known_open_items.md：{heading} 与台账实际数据不一致；"
                "请运行 make ledger-write"
            )

    start, end = locate_block(closed_lines, CLOSED_STATS_HEADING)
    actual = closed_lines[start : end + 1]
    expected = [BEGIN_LINE, *closed_block, END_LINE]
    if actual != expected:
        errors.append(
            "known_closed_items.md：0. 概览与索引实际数据不一致；"
            "请运行 make ledger-write"
        )
    return errors


def write_files(
    open_lines: list[str], closed_lines: list[str], validate_structure: bool = True
) -> None:
    """按两个台账的实际数据重写统计块。

    validate_structure=False 只用于自检构造负例；正常写盘必须拒绝不合法的台账。
    """
    open_parsed = parse_open(open_lines)
    closed_parsed = parse_closed(closed_lines)
    if validate_structure:
        errors = validate(open_parsed, closed_parsed)
        if errors:
            raise LedgerError(
                "台账结构不合法，拒绝生成统计：\n"
                + "\n".join(f"  - {e}" for e in errors)
            )

    open_blocks, closed_block = rendered_blocks(open_parsed, closed_parsed)
    for key, heading in OPEN_STATS_HEADINGS.items():
        write_block(open_lines, heading, open_blocks[key])
    write_block(closed_lines, CLOSED_STATS_HEADING, closed_block)


def self_test() -> int:
    """正例必须通过；每条负例必须报错（C7 区分力）。"""
    def open_ledger_with(status_rows: list[str]) -> list[str]:
        return [
            "# 测试开放式台账",
            "",
            "## 0. 未闭合看板",
            "",
            "### 0.1 状态统计",
            "",
            "| 状态 | 含义 | 数量 |",
            "|---|---|---:|",
            "| 占位 | x | 0 |",
            "",
            "### 0.6 按模块统计（未闭合 + 信息）",
            "",
            "| 模块 | 待决策 | 待定位 | 待验证 | 待实现 | 进行中 | 待外部 | 信息 | 合计 |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
            "| 1. 启动 / 掉电恢复 | 0 | 0 | 0 | 0 | 0 | 0 | 0 | 0 |",
            "",
            "## 1. 启动 / 掉电恢复",
            "",
            "### 索引",
            "",
            "| ID | 类型 | 状态 | 一句话 | 验证 |",
            "|---|---|---|---|---|",
            *status_rows,
            "",
            "# 附录 A：登记规则",
            "",
            "## A.5 归档",
            "",
            "- 已闭合 / 不实现迁入 known_closed_items.md。",
            "",
        ]

    def closed_ledger_with(
        closed_rows: list[str], notimpl_rows: list[str]
    ) -> list[str]:
        return [
            "# 测试已闭合台账",
            "",
            "## 0. 概览",
            "",
            "| 项 | 含义 | 数量 |",
            "|---|---:|---:|",
            "| 占位 | x | 0 |",
            "",
            "## 1. 已闭合索引",
            "",
            "| ID | 类型 | 模块 | 一句话 | 验证/归档 |",
            "|---|---|---|---|---|",
            *closed_rows,
            "",
            "## 2. 已闭合详情",
            "",
            "### 已闭合（详情见 archive）",
            "",
            "| ID | 日期 | 一句话 | 归档 |",
            "|---|---|---|---|",
            "| RISK-B-02 | 2026-11-14 | x | archive |",
            "",
            "## 3. 不实现",
            "",
            "| ID | 类型 | 模块 | 一句话 | 原因/归档 |",
            "|---|---|---|---|---|",
            *notimpl_rows,
            "",
        ]

    failures: list[str] = []
    cases = 0

    def require(name: str, ok: bool, detail: str = "") -> None:
        nonlocal cases
        cases += 1
        if not ok:
            suffix = f": {detail}" if detail else ""
            failures.append(f"{name}{suffix}")

    def expect(
        name: str, open_lines: list[str], closed_lines: list[str], should_pass: bool
    ) -> None:
        nonlocal cases
        cases += 1
        try:
            errors = check_files(open_lines, closed_lines)
        except LedgerError as exc:
            errors = [str(exc)]
        passed = not errors
        if passed != should_pass:
            failures.append(f"{name}: 期望{'通过' if should_pass else '报错'}，实际{errors}")

    closed_base = ["| RISK-B-01 | 风险 | 启动 / 掉电恢复 | x | y |"]
    open_base = ["| RISK-A-01 | 风险 | 信息 | x | y |"]
    base_open = open_ledger_with(open_base)
    base_closed = closed_ledger_with(closed_base, [])
    write_files(base_open, base_closed)
    expect("正例", base_open, base_closed, True)
    require("看板「## 0.」不计入模块统计", 0 not in parse_open(base_open)["modules"])

    bad_open = list(base_open)
    idx = next(i for i, line in enumerate(bad_open) if line.startswith("| 信息 |"))
    bad_open[idx] = "| 信息 | 判定结论/维护不变量 | 9 |"
    expect("开放式统计数字不符", bad_open, base_closed, False)

    bad_closed = list(base_closed)
    idx = next(i for i, line in enumerate(bad_closed) if line.startswith("| 已闭合 |"))
    bad_closed[idx] = "| 已闭合 | 有证据且无剩余动作 | 9 |"
    expect("已闭合概览数字不符", base_open, bad_closed, False)

    stray_open = open_ledger_with(["| RISK-A-01 | 风险 | 已闭合 | x | y |"])
    stray_closed = closed_ledger_with(closed_base, [])
    write_files(stray_open, stray_closed, validate_structure=False)
    expect("模块索引出现已闭合", stray_open, stray_closed, False)

    duplicate_open = open_ledger_with(["| RISK-A-01 | 风险 | 信息 | x | y |"])
    duplicate_closed = closed_ledger_with(
        ["| RISK-A-01 | 风险 | 启动 / 掉电恢复 | x | y |"], []
    )
    write_files(duplicate_open, duplicate_closed, validate_structure=False)
    expect("跨台账重复 ID", duplicate_open, duplicate_closed, False)

    notimpl_closed = closed_ledger_with(
        closed_base, ["| ISS-A-01 | 缺口 | 启动 / 掉电恢复 | x | y |"]
    )
    notimpl_open = open_ledger_with(open_base)
    write_files(notimpl_open, notimpl_closed)
    expect("不实现计数", notimpl_open, notimpl_closed, True)

    escaped_open = open_ledger_with(["| RISK-A-01 | 风险 | 信息 | CRC\\|MATA | y |"])
    escaped_closed = closed_ledger_with(closed_base, [])
    write_files(escaped_open, escaped_closed)
    expect("转义竖线 + 已闭合详情四列表", escaped_open, escaped_closed, True)

    numeric_open = open_ledger_with(["| RISK-L2P-01 | 风险 | 信息 | x | y |"])
    numeric_closed = closed_ledger_with(
        ["| RISK-L2P-02 | 风险 | 启动 / 掉电恢复 | x | y |"], []
    )
    write_files(numeric_open, numeric_closed)
    parsed_numeric_open = parse_open(numeric_open)
    parsed_numeric_closed = parse_closed(numeric_closed)
    require(
        "前缀含数字（RISK-L2P-*）计数",
        len(parsed_numeric_open["module_rows"]) == 1
        and len(parsed_numeric_closed["closed_rows"]) == 1,
        f"open={len(parsed_numeric_open['module_rows'])}, "
        f"closed={len(parsed_numeric_closed['closed_rows'])}",
    )
    expect("前缀含数字的 ID", numeric_open, numeric_closed, True)

    malformed_open = open_ledger_with(["| RISK-A-01 | 风险 | 信息 | x |"])
    malformed_closed = closed_ledger_with(closed_base, [])
    write_files(malformed_open, malformed_closed, validate_structure=False)
    expect("模块索引缺列", malformed_open, malformed_closed, False)

    closed_section_open = open_ledger_with(open_base)
    insert_at = closed_section_open.index("# 附录 A：登记规则")
    closed_section_open[insert_at:insert_at] = [
        "### 已闭合",
        "",
        "| ID | 日期 | 一句话 | 归档 |",
        "|---|---|---|---|",
        "| RISK-Z-01 | 2026-11-14 | x | archive |",
        "",
    ]
    closed_section_closed = closed_ledger_with(closed_base, [])
    write_files(closed_section_open, closed_section_closed, validate_structure=False)
    expect("开放台账残留已闭合小节", closed_section_open, closed_section_closed, False)

    if failures:
        print("ledger-test: FAIL")
        for failure in failures:
            print(f"  - {failure}")
        return 1

    print(f"ledger-test: OK ({cases} cases)")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="台账检查/统计生成")
    parser.add_argument("--root", default=".", help="仓库根目录")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true", help="校验统计块与结构")
    group.add_argument("--write", action="store_true", help="重写统计块")
    group.add_argument("--self-test", action="store_true", help="检查器自检")
    args = parser.parse_args(argv)

    if args.self_test:
        return self_test()

    open_path = Path(args.root) / OPEN_REL
    closed_path = Path(args.root) / CLOSED_REL
    for path in (open_path, closed_path):
        if not path.is_file():
            print(f"ledger-check: 找不到 {path}", file=sys.stderr)
            return 2

    open_lines = open_path.read_text(encoding="utf-8").splitlines()
    closed_lines = closed_path.read_text(encoding="utf-8").splitlines()

    try:
        if args.write:
            write_files(open_lines, closed_lines)
            open_path.write_text("\n".join(open_lines) + "\n", encoding="utf-8")
            closed_path.write_text("\n".join(closed_lines) + "\n", encoding="utf-8")
            print("ledger-write: OK (open 0.1/0.6 + closed 0. overview)")
            return 0

        errors = check_files(open_lines, closed_lines)
    except LedgerError as exc:
        print(f"ledger-check: ERROR: {exc}", file=sys.stderr)
        return 2

    if errors:
        print("ledger-check: FAIL")
        for error in errors:
            print(f"  - {error}")
        return 1

    open_parsed = parse_open(open_lines)
    closed_parsed = parse_closed(closed_lines)
    by_status, _, closed_count, notimpl_count = counts(open_parsed, closed_parsed)
    summary = " / ".join(f"{status}={by_status[status]}" for status in OPEN_STATUSES)
    print(
        f"ledger-check: OK (open={len(open_parsed['module_rows'])}; {summary}; "
        f"closed={closed_count}; not_impl={notimpl_count})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
